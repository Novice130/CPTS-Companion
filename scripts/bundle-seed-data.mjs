import { readFileSync, writeFileSync, existsSync } from "fs";
import { join } from "path";

const SEED_DIR = "./seed";
const OUTPUT_FILE = "./seed-data.ts";

const files = [
  "modules.json",
  "exercises.json",
  "flashcards.json",
  "mindmaps.json",
  "plan.json",
  "templates.json"
];

let output = "// Auto-generated by scripts/bundle-seed-data.mjs\n";

files.forEach(file => {
  const path = join(SEED_DIR, file);
  if (existsSync(path)) {
    const data = JSON.parse(readFileSync(path, "utf8"));
    const varName = file.replace(".json", "");
    output += `export const ${varName}Data = ${JSON.stringify(data, null, 2)};\n\n`;
  } else {
    const varName = file.replace(".json", "");
    output += `export const ${varName}Data = [];\n\n`;
  }
});

writeFileSync(OUTPUT_FILE, output);
console.log(`Successfully bundled seed data into ${OUTPUT_FILE}`);
