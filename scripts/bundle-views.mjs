import { readFileSync, writeFileSync, readdirSync, statSync } from "fs";
import { join, relative, extname } from "path";
import { Eta } from "eta";

const VIEWS_DIR = "./views";
const OUTPUT_FILE = "./views-manifest.ts";

// All top-level variables any template might receive from res.render()
const TEMPLATE_VARS = [
  'user', 'title', 'stats', 'dueCount', 'nextReview', 'settings',
  'currentPage', 'body', 'layout', 'pageTitle', 'metaDesc', 'ogPath',
  'modules', 'exercises', 'flashcards', 'notes', 'mindmaps', 'templates', 'categories',
  'module', 'exercise', 'flashcard', 'note', 'mindmap',
  'plan', 'planDays', 'dayProgress', 'todayActivities', 'reflection', 'recentNotes',
  'progress', 'allModules', 'relatedModules', 'nodeDataMap', 'nodeInfo',
  'dueFlashcards', 'commandExamplesHtml',
  'topic', 'prev', 'next', 'query', 'results', 'types', 'filters',
  'currentDay', 'planDuration', 'template', 'sanitize',
];

// Replace Eta's with(it||{}) with explicit destructuring (strict-mode compatible)
function transformBody(body) {
  const withRegex = /with\(it\|\|\{\}\)\{([\s\S]*)\}/;
  const m = body.match(withRegex);
  if (!m) return body;

  const before = body.slice(0, m.index);
  const content = m[1];
  const after = body.slice(m.index + m[0].length);

  // Skip any var already declared in the preamble (Eta helpers) or template body
  const alreadyDeclared = new Set();
  const declRe = /(?:var|let|const)\s+([\w$]+)/g;
  const fnRe = /function\s+([\w$]+)/g;
  for (const src of [before, content]) {
    let r;
    while ((r = declRe.exec(src)) !== null) alreadyDeclared.add(r[1]);
    while ((r = fnRe.exec(src)) !== null) alreadyDeclared.add(r[1]);
  }

  const safeVars = TEMPLATE_VARS.filter(v => !alreadyDeclared.has(v));
  const destruct = safeVars.length ? `const {${safeVars.join(', ')}} = it || {};` : '';
  return `${before}\n${destruct}\n${content}\n${after}`;
}

const eta = new Eta({ useWith: true, tags: ["<%", "%>"] });

function getAllFiles(dirPath, arrayOfFiles = []) {
  const files = readdirSync(dirPath);
  files.forEach(file => {
    if (statSync(dirPath + "/" + file).isDirectory()) {
      arrayOfFiles = getAllFiles(dirPath + "/" + file, arrayOfFiles);
    } else {
      arrayOfFiles.push(join(dirPath, "/", file));
    }
  });
  return arrayOfFiles;
}

const ejsFiles = getAllFiles(VIEWS_DIR).filter(f => extname(f) === ".ejs");
const compiled = {};

for (const file of ejsFiles) {
  let content = readFileSync(file, "utf8");
  // Convert EJS raw output tag `<%-` to Eta raw output tag `<%~`
  content = content.replace(/<%-/g, "<%~");
  const key = relative(VIEWS_DIR, file).replace(/\\/g, "/").replace(".ejs", "");
  try {
    const body = eta.compileToString(content);
    compiled[key] = transformBody(body);
  } catch (err) {
    console.error(`Compile error in ${key}:`, err.message);
    process.exit(1);
  }
}

const entries = Object.entries(compiled)
  .map(([k, body]) => `  ${JSON.stringify(k)}: function(it, options) {\n${body}\n  }`)
  .join(',\n');

const output = `// Auto-generated by scripts/bundle-views.mjs — DO NOT EDIT
// Templates pre-compiled at build time to avoid new Function() in CF Workers

type TemplateFn = (this: any, it: any, options?: any) => string;
export const viewsManifest: Record<string, TemplateFn> = {
${entries}
};
`;

writeFileSync(OUTPUT_FILE, output);
console.log(`Successfully pre-compiled ${ejsFiles.length} views into ${OUTPUT_FILE}`);
