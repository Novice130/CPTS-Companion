import { readFileSync, writeFileSync, readdirSync, statSync } from "fs";
import { join, relative, extname } from "path";

const VIEWS_DIR = "./views";
const OUTPUT_FILE = "./views-manifest.ts";

function getAllFiles(dirPath, arrayOfFiles) {
  const files = readdirSync(dirPath);

  arrayOfFiles = arrayOfFiles || [];

  files.forEach(function(file) {
    if (statSync(dirPath + "/" + file).isDirectory()) {
      arrayOfFiles = getAllFiles(dirPath + "/" + file, arrayOfFiles);
    } else {
      arrayOfFiles.push(join(dirPath, "/", file));
    }
  });

  return arrayOfFiles;
}

const allFiles = getAllFiles(VIEWS_DIR);
const ejsFiles = allFiles.filter(file => extname(file) === ".ejs");

const manifest = {};

ejsFiles.forEach(file => {
  const content = readFileSync(file, "utf8");
  const relativePath = relative(VIEWS_DIR, file).replace(/\\/g, "/");
  const key = relativePath.replace(".ejs", "");
  manifest[key] = content;
});

const output = `// Auto-generated by scripts/bundle-views.mjs
export const viewsManifest: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;

writeFileSync(OUTPUT_FILE, output);
console.log(`Successfully bundled ${ejsFiles.length} views into ${OUTPUT_FILE}`);
